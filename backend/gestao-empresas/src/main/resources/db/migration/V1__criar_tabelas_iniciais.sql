CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(45),
    edicao INTEGER,
    descricao VARCHAR(200),
    data_inicio DATE,
    data_fim DATE,
    local VARCHAR(200),
    status VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patrocinador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fantasia VARCHAR(45),
    razao_social VARCHAR(200),
    cnpj VARCHAR(20),
    email_contato VARCHAR(200),
    telefone VARCHAR(20),
    website VARCHAR(200),
    endereco JSONB,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    codigo VARCHAR(100),
    descricao VARCHAR(200),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(200) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    nome VARCHAR(200) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE perfil_role (
    perfil_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (perfil_id, role_id),
    CONSTRAINT fk_perfil_role_perfil
        FOREIGN KEY (perfil_id) REFERENCES perfil(id),
    CONSTRAINT fk_perfil_role_role
        FOREIGN KEY (role_id) REFERENCES role(id)
);

CREATE TABLE role_permissao (
    role_id BIGINT NOT NULL,
    permissao_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permissao_id),
    CONSTRAINT fk_role_permissao_role
        FOREIGN KEY (role_id) REFERENCES role(id),
    CONSTRAINT fk_role_permissao_permissao
        FOREIGN KEY (permissao_id) REFERENCES permissao(id)
);

CREATE TABLE plano_comercial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(20),
    descricao VARCHAR(200),
    status VARCHAR(45),
    valido_de DATE,
    valido_ate DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_evento BIGINT,
    CONSTRAINT fk_plano_comercial_evento
        FOREIGN KEY (id_evento) REFERENCES evento(id)
);

CREATE TABLE contato_patrocinador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinador BIGINT,
    nome VARCHAR(200),
    email_contato VARCHAR(200),
    telefone VARCHAR(20),
    cargo VARCHAR(200),
    tipo_contato VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contato_patrocinador_patrocinador
        FOREIGN KEY (id_patrocinador) REFERENCES patrocinador(id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinador BIGINT,
    nome VARCHAR(200),
    email VARCHAR(200),
    senha_hash VARCHAR(200),
    telefone VARCHAR(30),
    status VARCHAR(30),
    ultimo_acesso TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_perfil BIGINT,
    CONSTRAINT fk_usuario_patrocinador
        FOREIGN KEY (id_patrocinador) REFERENCES patrocinador(id),
    CONSTRAINT fk_usuario_perfil
        FOREIGN KEY (id_perfil) REFERENCES perfil(id)
);

CREATE TABLE cota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(45),
    nome VARCHAR(20),
    id_plano_comercial BIGINT,
    descricao VARCHAR(200),
    valor NUMERIC(10, 2),
    limite_patrocinio INTEGER,
    ordem INTEGER,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    beneficios JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cota_plano_comercial
        FOREIGN KEY (id_plano_comercial) REFERENCES plano_comercial(id)
);

CREATE TABLE email_liberado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cadastrado_por_usuario BIGINT,
    aceito_por_usuario BIGINT,
    id_patrocinador BIGINT,
    id_perfil BIGINT,
    email VARCHAR(200),
    status_convite VARCHAR(30),
    token_hash VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_email_liberado_cadastrado_por
        FOREIGN KEY (cadastrado_por_usuario) REFERENCES usuario(id),
    CONSTRAINT fk_email_liberado_aceito_por
        FOREIGN KEY (aceito_por_usuario) REFERENCES usuario(id),
    CONSTRAINT fk_email_liberado_patrocinador
        FOREIGN KEY (id_patrocinador) REFERENCES patrocinador(id),
    CONSTRAINT fk_email_liberado_perfil
        FOREIGN KEY (id_perfil) REFERENCES perfil(id)
);

CREATE TABLE cota_modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modulo BIGINT,
    id_cota BIGINT,
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_cota_modulo_modulo
        FOREIGN KEY (id_modulo) REFERENCES modulo(id),
    CONSTRAINT fk_cota_modulo_cota
        FOREIGN KEY (id_cota) REFERENCES cota(id)
);

CREATE TABLE patrocinio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cota BIGINT,
    status VARCHAR(30),
    valor_acordado NUMERIC(10, 2),
    data_contratacao DATE,
    data_inicio TIMESTAMP WITH TIME ZONE,
    data_fim TIMESTAMP WITH TIME ZONE,
    observacao VARCHAR(200),
    id_evento BIGINT,
    id_patrocinador BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_patrocinio_cota
        FOREIGN KEY (id_cota) REFERENCES cota(id),
    CONSTRAINT fk_patrocinio_evento
        FOREIGN KEY (id_evento) REFERENCES evento(id),
    CONSTRAINT fk_patrocinio_patrocinador
        FOREIGN KEY (id_patrocinador) REFERENCES patrocinador(id)
);
