
CREATE TABLE veiculacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_midia_id BIGINT NOT NULL,
    canal VARCHAR(100) NOT NULL,
    inicio TIMESTAMP WITH TIME ZONE,
    fim TIMESTAMP WITH TIME ZONE,
    status VARCHAR(30) NOT NULL DEFAULT 'PREVISTA',
    metricas JSONB NOT NULL DEFAULT '{}'::jsonb,
    observacoes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_veiculacao_material_midia FOREIGN KEY (material_midia_id) REFERENCES material_midia(id),
    CONSTRAINT ck_veiculacao_status CHECK (status IN ('PREVISTA', 'NO_AR', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_veiculacao_datas CHECK (inicio IS NULL OR fim IS NULL OR fim >= inicio)
);
CREATE INDEX idx_veiculacao_material_midia_id ON veiculacao (material_midia_id);

CREATE TABLE conversa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patrocinio_id BIGINT NOT NULL,
    assunto VARCHAR(180) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ABERTA',
    criada_por_usuario_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversa_patrocinio FOREIGN KEY (patrocinio_id) REFERENCES patrocinio(id),
    CONSTRAINT fk_conversa_criada_por FOREIGN KEY (criada_por_usuario_id) REFERENCES usuario(id),
    CONSTRAINT ck_conversa_status CHECK (status IN ('ABERTA', 'FECHADA'))
);
CREATE INDEX idx_conversa_patrocinio_id ON conversa (patrocinio_id);
CREATE INDEX idx_conversa_criada_por_id ON conversa (criada_por_usuario_id);

CREATE TABLE mensagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_id BIGINT,
    conversa_id BIGINT NOT NULL,
    conteudo TEXT NOT NULL,
    enviada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida_em TIMESTAMP WITH TIME ZONE,
    remetente_usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_mensagem_arquivo FOREIGN KEY (arquivo_id) REFERENCES arquivo(id),
    CONSTRAINT fk_mensagem_conversa FOREIGN KEY (conversa_id) REFERENCES conversa(id),
    CONSTRAINT fk_mensagem_remetente FOREIGN KEY (remetente_usuario_id) REFERENCES usuario(id)
);
CREATE INDEX idx_mensagem_conversa_data ON mensagem (conversa_id, enviada_em);
CREATE INDEX idx_mensagem_arquivo_id ON mensagem (arquivo_id);
CREATE INDEX idx_mensagem_remetente_id ON mensagem (remetente_usuario_id);

CREATE TABLE faq (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT,
    criada_por_usuario_id BIGINT,
    pergunta TEXT NOT NULL,
    resposta TEXT NOT NULL,
    categoria VARCHAR(100),
    ordem INTEGER NOT NULL DEFAULT 0,
    publicada BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_faq_evento FOREIGN KEY (evento_id) REFERENCES evento(id),
    CONSTRAINT fk_faq_criada_por FOREIGN KEY (criada_por_usuario_id) REFERENCES usuario(id)
);
CREATE INDEX idx_faq_evento_id ON faq (evento_id);
CREATE INDEX idx_faq_criada_por_id ON faq (criada_por_usuario_id);

CREATE TABLE resposta_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    token_respondente_hash VARCHAR(255),
    iniciada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviada_em TIMESTAMP WITH TIME ZONE,
    pesquisa_id BIGINT NOT NULL,
    CONSTRAINT fk_resposta_pesquisa_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_resposta_pesquisa_pesquisa FOREIGN KEY (pesquisa_id) REFERENCES pesquisa(id)
);
CREATE INDEX idx_resposta_pesquisa_usuario_id ON resposta_pesquisa (usuario_id);
CREATE INDEX idx_resposta_pesquisa_pesquisa_id ON resposta_pesquisa (pesquisa_id);

CREATE TABLE resposta_pergunta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resposta_pesquisa_id BIGINT NOT NULL,
    pergunta_pesquisa_id BIGINT NOT NULL,
    resposta JSONB NOT NULL DEFAULT '{}'::jsonb,
    respondida_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_resposta_pergunta_resposta FOREIGN KEY (resposta_pesquisa_id) REFERENCES resposta_pesquisa(id),
    CONSTRAINT fk_resposta_pergunta_pergunta FOREIGN KEY (pergunta_pesquisa_id) REFERENCES pergunta_pesquisa(id),
    CONSTRAINT uq_resposta_pergunta_1 UNIQUE (resposta_pesquisa_id, pergunta_pesquisa_id)
);
CREATE INDEX idx_resposta_pergunta_pergunta_id ON resposta_pergunta (pergunta_pesquisa_id);

CREATE TABLE usuario_patrocinio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    patrocinio_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_patrocinio_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_usuario_patrocinio_patrocinio FOREIGN KEY (patrocinio_id) REFERENCES patrocinio(id),
    CONSTRAINT uq_usuario_patrocinio_1 UNIQUE (usuario_id, patrocinio_id)
);
CREATE INDEX idx_usuario_patrocinio_patrocinio_id ON usuario_patrocinio (patrocinio_id);

CREATE TABLE recuperacao_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    valido_ate TIMESTAMP WITH TIME ZONE NOT NULL,      -- o service define (ex.: agora + 1h); sem default
    usado_em TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recuperacao_senha_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);
CREATE INDEX idx_recuperacao_senha_usuario_id ON recuperacao_senha (usuario_id);