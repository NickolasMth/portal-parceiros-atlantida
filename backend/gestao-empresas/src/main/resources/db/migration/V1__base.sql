CREATE INDEX idx_usuario_patrocinador_id ON usuario (patrocinador_id);
CREATE INDEX idx_usuario_perfil_id ON usuario (perfil_id);
CREATE INDEX idx_cota_plano_comercial_id ON cota (plano_comercial_id);
CREATE INDEX idx_email_liberado_patrocinador_id ON email_liberado (patrocinador_id);
