CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    edicao INTEGER NOT NULL,
    descricao VARCHAR(200),
    data_inicio DATE,
    data_fim DATE,
    local VARCHAR(200),
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_evento_1 UNIQUE (nome, edicao),
    CONSTRAINT ck_evento_status CHECK (status IN ('PLANEJADO', 'ATIVO', 'ENCERRADO')),
    CONSTRAINT ck_evento_datas CHECK (data_inicio IS NULL OR data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE TABLE patrocinador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fantasia VARCHAR(120) NOT NULL,
    razao_social VARCHAR(200),
    cnpj VARCHAR(20) UNIQUE,
    email_contato VARCHAR(200),
    telefone VARCHAR(20),
    website VARCHAR(200),
    endereco JSONB,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(200),
    ordem INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(200) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    nome VARCHAR(200) NOT NULL,
    descricao VARCHAR(300),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE perfil_role (
    perfil_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (perfil_id, role_id),
    CONSTRAINT fk_perfil_role_perfil FOREIGN KEY (perfil_id) REFERENCES perfil(id) ON DELETE CASCADE,
    CONSTRAINT fk_perfil_role_role FOREIGN KEY (role_id) REFERENCES role(id) ON DELETE CASCADE
);

CREATE TABLE role_permissao (
    role_id BIGINT NOT NULL,
    permissao_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permissao_id),
    CONSTRAINT fk_role_permissao_role FOREIGN KEY (role_id) REFERENCES role(id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissao_permissao FOREIGN KEY (permissao_id) REFERENCES permissao(id) ON DELETE CASCADE
);

CREATE TABLE plano_comercial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    descricao VARCHAR(200),
    status VARCHAR(45) NOT NULL DEFAULT 'ATIVO',
    valido_de DATE,
    valido_ate DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    evento_id BIGINT NOT NULL,
    CONSTRAINT fk_plano_comercial_evento FOREIGN KEY (evento_id) REFERENCES evento(id),
    CONSTRAINT ck_plano_comercial_validade CHECK (valido_de IS NULL OR valido_ate IS NULL OR valido_ate >= valido_de)
);

CREATE TABLE contato_patrocinador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patrocinador_id BIGINT NOT NULL,
    nome VARCHAR(200) NOT NULL,
    email_contato VARCHAR(200),
    telefone VARCHAR(20),
    cargo VARCHAR(200),
    tipo_contato VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contato_patrocinador_patrocinador FOREIGN KEY (patrocinador_id) REFERENCES patrocinador(id)
);

CREATE UNIQUE INDEX uq_contato_principal ON contato_patrocinador (patrocinador_id) WHERE principal;

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patrocinador_id BIGINT,
    nome VARCHAR(200) NOT NULL,
    email VARCHAR(200) NOT NULL,
    senha_hash VARCHAR(200) NOT NULL,
    telefone VARCHAR(30),
    status VARCHAR(30) NOT NULL DEFAULT 'ATIVO',
    ultimo_acesso TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    perfil_id BIGINT NOT NULL,
    CONSTRAINT fk_usuario_patrocinador FOREIGN KEY (patrocinador_id) REFERENCES patrocinador(id),
    CONSTRAINT fk_usuario_perfil FOREIGN KEY (perfil_id) REFERENCES perfil(id),
    CONSTRAINT ck_usuario_status CHECK (status IN ('PENDENTE', 'ATIVO', 'INATIVO', 'BLOQUEADO'))
);

CREATE UNIQUE INDEX uq_usuario_email ON usuario (LOWER(email));

CREATE TABLE cota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(45) NOT NULL,
    nome VARCHAR(60) NOT NULL,
    plano_comercial_id BIGINT NOT NULL,
    descricao VARCHAR(200),
    valor NUMERIC(14, 2) CHECK (valor >= 0),
    limite_patrocinio INTEGER CHECK (limite_patrocinio >= 0),
    ordem INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    beneficios JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cota_plano_comercial FOREIGN KEY (plano_comercial_id) REFERENCES plano_comercial(id),
    CONSTRAINT uq_cota_1 UNIQUE (plano_comercial_id, codigo)
);

CREATE TABLE email_liberado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cadastrado_por_usuario_id BIGINT,
    aceito_por_usuario_id BIGINT,
    patrocinador_id BIGINT,
    perfil_id BIGINT NOT NULL,
    email VARCHAR(200) NOT NULL,
    status_convite VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
    token_hash VARCHAR(200) NOT NULL UNIQUE,
    valido_ate TIMESTAMP WITH TIME ZONE,
    aceito_em TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_email_liberado_cadastrado_por FOREIGN KEY (cadastrado_por_usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_email_liberado_aceito_por FOREIGN KEY (aceito_por_usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_email_liberado_patrocinador FOREIGN KEY (patrocinador_id) REFERENCES patrocinador(id),
    CONSTRAINT fk_email_liberado_perfil FOREIGN KEY (perfil_id) REFERENCES perfil(id),
    CONSTRAINT ck_email_liberado_status CHECK (status_convite IN ('PENDENTE', 'ACEITO', 'EXPIRADO', 'REVOGADO'))
);

CREATE UNIQUE INDEX uq_email_liberado_pendente ON email_liberado (LOWER(email)) WHERE status_convite = 'PENDENTE';

CREATE TABLE cota_modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id BIGINT NOT NULL,
    cota_id BIGINT NOT NULL,
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_cota_modulo_modulo FOREIGN KEY (modulo_id) REFERENCES modulo(id),
    CONSTRAINT fk_cota_modulo_cota FOREIGN KEY (cota_id) REFERENCES cota(id),
    CONSTRAINT uq_cota_modulo_1 UNIQUE (modulo_id, cota_id)
);

CREATE TABLE patrocinio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cota_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ATIVO',
    valor_acordado NUMERIC(14, 2) CHECK (valor_acordado >= 0),
    data_contratacao DATE,
    data_inicio DATE,
    data_fim DATE,
    observacao VARCHAR(200),
    evento_id BIGINT NOT NULL,
    patrocinador_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_patrocinio_cota FOREIGN KEY (cota_id) REFERENCES cota(id),
    CONSTRAINT fk_patrocinio_evento FOREIGN KEY (evento_id) REFERENCES evento(id),
    CONSTRAINT fk_patrocinio_patrocinador FOREIGN KEY (patrocinador_id) REFERENCES patrocinador(id),
    CONSTRAINT uq_patrocinio_1 UNIQUE (evento_id, patrocinador_id),
    CONSTRAINT ck_patrocinio_status CHECK (status IN ('PROSPECTO', 'CONTRATADO', 'ATIVO', 'ENCERRADO', 'CANCELADO')),
    CONSTRAINT ck_patrocinio_datas CHECK (data_inicio IS NULL OR data_fim IS NULL OR data_fim >= data_inicio)
);


CREATE INDEX idx_plano_comercial_evento_id ON plano_comercial (evento_id);
