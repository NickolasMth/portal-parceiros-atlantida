CREATE TABLE arquivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key VARCHAR(500) NOT NULL UNIQUE,
    nome_original VARCHAR(255) NOT NULL,
    mime_type VARCHAR(150) NOT NULL,
    tamanho_bytes BIGINT NOT NULL CHECK (tamanho_bytes >= 0),
    checksum VARCHAR(128),                             -- SHA-256, para auditoria
    metadados JSONB NOT NULL DEFAULT '{}'::jsonb,
    patrocinio_id BIGINT,                              -- dono do arquivo (NULL = arquivo geral, só RBS)
    categoria VARCHAR(40),                             -- PLANO_COMERCIAL, MIV, LOGO, FOTO_ATIVACAO, CONTRATO, RELATORIO...
    enviado_por_usuario_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_arquivo_patrocinio FOREIGN KEY (patrocinio_id) REFERENCES patrocinio(id),
    CONSTRAINT fk_arquivo_enviado_por_usuario FOREIGN KEY (enviado_por_usuario_id) REFERENCES usuario(id)
);
CREATE INDEX idx_arquivo_patrocinio_categoria ON arquivo (patrocinio_id, categoria);
CREATE INDEX idx_arquivo_enviado_por_usuario_id ON arquivo (enviado_por_usuario_id);

