    quantidade_respostas INTEGER NOT NULL DEFAULT 0 CHECK (quantidade_respostas >= 0),
    dados_agregados JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_resultado_pesquisa_pergunta FOREIGN KEY (pergunta_pesquisa_id) REFERENCES pergunta_pesquisa(id)
);

