CREATE TABLE pergunta_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado TEXT NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    obrigatoria BOOLEAN NOT NULL DEFAULT FALSE,
    ordem INTEGER NOT NULL DEFAULT 0,
    opcoes JSONB,
    configuracoes JSONB NOT NULL DEFAULT '{}'::jsonb,
    patrocinio_id BIGINT,                              -- ADICIONADO: NULL = pergunta oficial; preenchido = pergunta do cliente
    pesquisa_id BIGINT NOT NULL,
    CONSTRAINT fk_pergunta_pesquisa_patrocinio FOREIGN KEY (patrocinio_id) REFERENCES patrocinio(id),
    CONSTRAINT fk_pergunta_pesquisa_pesquisa FOREIGN KEY (pesquisa_id) REFERENCES pesquisa(id),
    CONSTRAINT ck_pergunta_pesquisa_tipo CHECK (tipo IN ('TEXTO', 'MULTIPLA_ESCOLHA', 'ESCALA', 'SIM_NAO')),
    -- o TAP dá ao cliente direito a 3 perguntas: ordem 1, 2 ou 3
    CONSTRAINT ck_pergunta_pesquisa_max3 CHECK (patrocinio_id IS NULL OR ordem BETWEEN 1 AND 3)
);
CREATE UNIQUE INDEX uq_pergunta_oficial_ordem ON pergunta_pesquisa (pesquisa_id, ordem) WHERE patrocinio_id IS NULL;
CREATE UNIQUE INDEX uq_pergunta_cliente_ordem ON pergunta_pesquisa (pesquisa_id, patrocinio_id, ordem) WHERE patrocinio_id IS NOT NULL;
CREATE INDEX idx_pergunta_pesquisa_patrocinio_id ON pergunta_pesquisa (patrocinio_id);

CREATE TABLE resultado_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta_pesquisa_id BIGINT NOT NULL UNIQUE,       -- um resultado por pergunta (a pesquisa já vem da pergunta)
